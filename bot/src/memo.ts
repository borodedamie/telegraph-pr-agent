import type { LedgerRow } from "./ledger.js";

export const MEMO_MARKER = "<!-- telegraph-pr-agent-memo -->";

export interface MemoOptions {
  prNumber: number;
  dashboardUrl: string;
}

const EXPLORER = "https://sepolia.basescan.org/tx/";

const BOUNDARY =
  "Testnet build. Routing, miners, verification and settlement are real; " +
  "USDC is testnet-denominated. No revenue claim is made.";

function utc(ts: string): string {
  const d = new Date(ts);
  const pad = (n: number) => String(n).padStart(2, "0");
  return `${d.getUTCFullYear()}-${pad(d.getUTCMonth() + 1)}-${pad(d.getUTCDate())} ${pad(d.getUTCHours())}:${pad(d.getUTCMinutes())} UTC`;
}

const usdc = (n: number) => n.toFixed(2);
const task = (intent: string) => intent.replace(/_/g, " ");

// Markdown blockquote: every line needs its own `>` or the quote ends early.
const quote = (text: string) => text.split("\n").map((l) => `> ${l}`).join("\n");

function receipt(r: LedgerRow): string {
  const settled = r.status === "settled";
  const sentence = settled
    ? `Paid **${usdc(r.amountUsdc)} USDC** to **${r.minerName}** for **${task(r.intent)}** on **PR #${r.prNumber}**.`
    : `Payment of **${usdc(r.amountUsdc)} USDC** to **${r.minerName}** for **${task(r.intent)}** on **PR #${r.prNumber}** didn’t go through.`;
  const foot = settled
    ? `settled · ${utc(r.timestamp)} · miner \`${r.minerId}\` · [View payment ↗](${EXPLORER}${r.txHash})`
    : `failed · ${utc(r.timestamp)} · miner \`${r.minerId}\``;
  return [sentence, "", quote(r.answer), "", `<sub>${foot}</sub>`].join("\n");
}

export function renderMemo(rows: LedgerRow[], opts: MemoOptions): string {
  const settled = rows.filter((r) => r.status === "settled");
  const total = settled.reduce((sum, r) => sum + r.amountUsdc, 0);
  const failed = rows.length - settled.length;

  return [
    MEMO_MARKER,
    `### 🧾 Telegraph — spend memo · PR #${opts.prNumber}`,
    "",
    `**${settled.length} SETTLED · ${usdc(total)} USDC PAID · ${failed} FAILED** · Base Sepolia \`(eip155:84532)\``,
    "",
    `> ${BOUNDARY}`,
    "",
    ...rows.map((r) => ["---", "", receipt(r), ""].join("\n")),
    "---",
    "",
    `📊 [Open the spend dashboard →](${opts.dashboardUrl}) — head SHA, miner IDs, tx hashes and full answers live there.`,
    "",
    "<sub>Generated by telegraph-pr-agent · x402 on Base Sepolia</sub>",
    "",
  ].join("\n");
}
